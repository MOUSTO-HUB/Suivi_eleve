import { versE164 } from './validation.js';

describe('versE164', () => {
  it.each([
    ['+221 77 123 45 67', '221', '+221771234567'],
    ['77 123 45 67', '221', '+221771234567'],
    ['771234567', '221', '+221771234567'],
    ['00221771234567', '221', '+221771234567'],
    ['221771234567', '221', '+221771234567'],
    ['+33 6 12 34 56 78', '221', '+33612345678'],
    ['77.123.45.67', '221', '+221771234567'],
    // Guinée et Côte d'Ivoire : l'indicatif de l'école s'applique.
    ['621 12 34 56', '224', '+224621123456'],
    ['07 12 34 56 78', '225', '+2250712345678'],
  ])('%s (indicatif %s) → %s', (entree, indicatif, attendu) => {
    expect(versE164(entree, indicatif)).toBe(attendu);
  });
});
